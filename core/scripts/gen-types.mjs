#!/usr/bin/env node
// Generates the IR types from core/schema (M1.6):
//   core/src/generated/ir.ts               json-schema-to-typescript
//   core/py/src/cinewright_ir/models.py    datamodel-code-generator (Pydantic v2)
//   core/test/generated/fixtures.ts        every valid schema fixture, typed with `satisfies`
// `--check` regenerates into a temporary directory and fails if any committed output differs.
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const CORE = fileURLToPath(new URL("..", import.meta.url));
const REPO = join(CORE, "..");
const SCHEMA_DIR = join(CORE, "schema");
const FIXTURE_DIR = join(CORE, "test", "fixtures", "schema");
const OUTPUTS = {
  ts: join(CORE, "src", "generated", "ir.ts"),
  py: join(CORE, "py", "src", "cinewright_ir", "models.py"),
  fixtures: join(CORE, "test", "generated", "fixtures.ts"),
};
const HEADER = "Generated by core/scripts/gen-types.mjs from core/schema. Do not edit.";

/** Fixture directory → the generated type its valid documents must satisfy. */
const FIXTURE_TYPES = {
  "delivery-profile": "DeliveryProfile",
  project: "Project",
};

const check = process.argv.includes("--check");

function documentSchemas() {
  return readdirSync(SCHEMA_DIR)
    .filter((name) => name.endsWith(".schema.json") && name !== "common.schema.json")
    .sort();
}

/** A copy of core/schema plus a root that references every document schema, so each type is emitted once. */
function stageSchemas(dir) {
  for (const name of readdirSync(SCHEMA_DIR)) {
    if (name.endsWith(".schema.json")) copyFileSync(join(SCHEMA_DIR, name), join(dir, name));
  }
  const properties = {};
  for (const name of documentSchemas()) {
    properties[name.replace(/\.schema\.json$/, "").replace(/-/g, "_")] = { $ref: name };
  }
  const root = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://cinewright.invalid/ir/0/_documents.schema.json",
    title: "IrDocuments",
    description: "Every IR document schema; exists only so each type is generated once.",
    type: "object",
    additionalProperties: false,
    properties,
  };
  const path = join(dir, "_documents.schema.json");
  writeFileSync(path, `${JSON.stringify(root, null, 2)}\n`);
  return path;
}

async function generateTs(rootPath, stageDir) {
  return compileFromFile(rootPath, {
    cwd: stageDir,
    bannerComment: `// ${HEADER}`,
    additionalProperties: false,
    unknownAny: true,
    format: true,
  });
}

function generatePy(rootPath, outPath) {
  execFileSync(
    "uv",
    [
      "run",
      "--locked",
      "datamodel-codegen",
      "--input",
      rootPath,
      "--input-file-type",
      "jsonschema",
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.13",
      "--use-title-as-name",
      "--use-standard-collections",
      "--use-union-operator",
      "--use-annotated",
      "--field-constraints",
      "--extra-fields",
      "forbid",
      "--disable-timestamp",
      "--formatters",
      "ruff-format",
      "--custom-file-header",
      `# ${HEADER}`,
      "--output",
      outPath,
    ],
    { cwd: REPO, stdio: ["ignore", "ignore", "inherit"] },
  );
  return readFileSync(outPath, "utf8");
}

function exportName(dir, name) {
  const words = `${dir}-${name.replace(/\.json$/, "")}`.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  return words.map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join("");
}

function generateFixtures() {
  const used = new Set();
  const lines = [];
  for (const dir of readdirSync(FIXTURE_DIR).sort()) {
    const type = FIXTURE_TYPES[dir];
    if (!type)
      throw new Error(`gen-types: no type for fixture directory ${dir}; add it to FIXTURE_TYPES`);
    let names = [];
    try {
      names = readdirSync(join(FIXTURE_DIR, dir, "valid")).filter((n) => n.endsWith(".json"));
    } catch {
      continue;
    }
    for (const name of names.sort()) {
      used.add(type);
      const data = JSON.parse(readFileSync(join(FIXTURE_DIR, dir, "valid", name), "utf8"));
      lines.push(
        `export const ${exportName(dir, name)} = ${JSON.stringify(data, null, 2)} satisfies ${type};`,
      );
    }
  }
  const imports = [...used].sort().join(", ");
  return `// ${HEADER}\nimport type { ${imports} } from "../../src/generated/ir.js";\n\n${lines.join("\n\n")}\n`;
}

const stage = mkdtempSync(join(tmpdir(), "cinewright-gen-"));
try {
  const rootPath = stageSchemas(stage);
  const outputs = {
    ts: await generateTs(rootPath, stage),
    py: generatePy(rootPath, join(stage, "models.py")),
    fixtures: generateFixtures(),
  };
  const drifted = [];
  for (const [key, content] of Object.entries(outputs)) {
    const target = OUTPUTS[key];
    let current = null;
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current === content) continue;
    if (check) drifted.push(target.slice(REPO.length + 1));
    else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
  if (drifted.length > 0) {
    console.error(`generated types are out of date: ${drifted.join(", ")}\nrun: pnpm gen:types`);
    process.exitCode = 1;
  }
} finally {
  rmSync(stage, { recursive: true, force: true });
}
